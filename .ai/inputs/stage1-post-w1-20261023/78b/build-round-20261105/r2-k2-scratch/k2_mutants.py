def main():
    kit = pathlib.Path(sys.argv[1])
    texts = {}
    bad = []
    for mid, part, f, find, rep, desc in M:
        t = texts.setdefault(f, (kit / f).read_text())
        n = t.count(find)
        if n != 1 or find == rep:
            bad.append((mid, f, n))
    print(json.dumps({"mutants": len(M), "bad": bad}))
    if "--write" in sys.argv and not bad:
        spec_path = kit / "tests" / "mutation_spec_scorer_78b.json"
        spec = json.loads(spec_path.read_text())
        ids = {m["id"] for m in spec["mutants"]}
        dup = [m[0] for m in M if m[0] in ids]
        if dup:
            raise SystemExit(f"already in the spec: {dup}")
        for mid, part, f, find, rep, desc in M:
            spec["mutants"].append({"id": mid, "part": part, "describes": desc, "file": f, "find": find, "replace": rep})
        spec_path.write_text(json.dumps(spec, indent=1, ensure_ascii=False) + "\n")
        print("written", len(spec["mutants"]))


if __name__ == "__main__":
    main()
