"""Pack the round-1 setup for the headroom positive control (administrative; never includes credentials or .ai).

    python3.11 pack_setup.py --recipe experiments/safety_selection/configs/RECIPE.json

Writes, once (refuses to overwrite):
  setup/bundle-hr-v1.tar.gz       engine code (minimal_safety, safety_selection), the A100 fixture script,
                                  bootstrap_hr.sh, requirements.lock and bundle-manifest.json
  setup/worker_bootstrap_hr.sh    the bootstrap with the bundle's and the data's SHA-256 written in
  setup/worker-setup-hr.tar.gz    everything a pod needs before the plan: the scripts above, the bundle,
                                  expanded-assets-v2.tar.gz (prepared-v2, unchanged), the model download and runners
  setup/setup-receipt.json        hashes of all of it, and the engine code identity of the packed code
"""
import argparse, hashlib, io, json, pathlib, subprocess, tarfile, time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SETUP = HERE / "setup"
OLD = ROOT / "tmp/study-v2-20261002"
ASSETS, ASSETS_SHA = OLD / "expanded-assets-v2.tar.gz", "c294de4e95ab20906dd8ce39bc4a2f7d31a0709a974593c9ac07ab122bcbef83"
PY = ROOT / "tmp/minimal-experiment-20261002/venv/bin/python"


def sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tar(dest: pathlib.Path, files: dict, extra: dict | None = None) -> None:
    with dest.open("xb") as handle:
        with tarfile.open(fileobj=handle, mode="w:gz") as archive:
            for name, f in sorted(files.items()):
                digest = sha(f)
                archive.add(f, arcname=name, recursive=False)
                assert sha(f) == digest, f"{f} changed while packing"
            for name, payload in (extra or {}).items():
                entry = tarfile.TarInfo(name); entry.size = len(payload); entry.mtime = int(time.time())
                archive.addfile(entry, io.BytesIO(payload))


def main() -> None:
    ap = argparse.ArgumentParser(); ap.add_argument("--recipe", required=True); a = ap.parse_args()
    assert (ROOT / a.recipe).is_file(), a.recipe
    assert sha(ASSETS) == ASSETS_SHA, "expanded-assets-v2 changed"
    status = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--", "experiments", "scripts"],
                            capture_output=True, text=True, check=True).stdout
    assert not status.strip(), f"engine files are not committed:\n{status}"
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    files = {}
    for component in ("minimal_safety", "safety_selection"):
        for f in (ROOT / "experiments" / component).rglob("*"):
            if (f.is_file() and not f.is_symlink() and "__pycache__" not in f.parts and ".pytest_cache" not in f.parts
                    and f.suffix in {".py", ".json", ".md", ".lock"}):
                files[str(f.relative_to(ROOT))] = f
    init = ROOT / "experiments/__init__.py"
    if init.exists():
        files["experiments/__init__.py"] = init
    files["scripts/cuda_preflight_headroom.py"] = ROOT / "scripts/cuda_preflight_headroom.py"
    files["bootstrap_hr.sh"] = SETUP / "bootstrap_hr.sh"
    files["requirements.lock"] = ROOT / "experiments/minimal_safety/requirements.lock"
    manifest = {"kind": "explicit code export for the headroom positive control; no credentials", "git_commit": commit,
                "files": {name: sha(f) for name, f in sorted(files.items())}}
    bundle = SETUP / "bundle-hr-v1.tar.gz"
    tar(bundle, files, {"bundle-manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()})
    code = subprocess.run([str(PY), "-c", "from experiments.safety_selection.common import code_identity;"
                                          "print(code_identity()['sha256'])"], cwd=ROOT, capture_output=True, text=True,
                          check=True, env={"PYTHONDONTWRITEBYTECODE": "1", "PATH": "/usr/bin:/bin"}).stdout.strip()
    bundle_sha = sha(bundle)
    bootstrap = f"""#!/bin/bash
# Generated by pack_setup.py: environment, models, bundle and data checks, then the two-step A100 fixture.
set -euo pipefail
cd /workspace/attribution-headroom
export CUBLAS_WORKSPACE_CONFIG=:4096:8 CUDA_VISIBLE_DEVICES=0 TOKENIZERS_PARALLELISM=false OMP_NUM_THREADS=4 MKL_NUM_THREADS=4 PYTHONPATH=/workspace/attribution-headroom
python3 process_receipt.py --out setup-001 -- bash setup_and_fetch_hr.sh "$@"
venv/bin/python - <<'PY'
import hashlib,json,pathlib,tarfile
for name,digest,manifest in [('bundle-hr-v1.tar.gz','{bundle_sha}','bundle-manifest.json'),('expanded-assets-v2.tar.gz','{ASSETS_SHA}','expanded-assets-manifest.json')]:
    p=pathlib.Path(name);assert hashlib.sha256(p.read_bytes()).hexdigest()==digest,name
    with tarfile.open(p) as t:t.extractall('.',filter='data')
    m=json.loads(pathlib.Path(manifest).read_text());m=m.get('files',m)
    for f,h in m.items():assert hashlib.sha256(pathlib.Path(f).read_bytes()).hexdigest()==h,f
from experiments.safety_selection.common import code_identity
assert code_identity()['sha256']=='{code}','engine code identity differs from the packed code'
import torch
assert torch.cuda.get_device_name(0)=='NVIDIA A100-SXM4-80GB'
PY
python3 process_receipt.py --out preflight-process-001 -- venv/bin/python scripts/cuda_preflight_headroom.py --recipe {a.recipe} --prepared prepared-v2 --out cuda-preflight-hr-001
venv/bin/python - <<'PY'
import datetime,hashlib,json,pathlib
v=pathlib.Path('cuda-preflight-hr-001/verification.json');x=json.loads(v.read_text())
ok=x.get('resume',{{}}).get('exact') is True
pathlib.Path('PREFLIGHT-DONE.json').write_text(json.dumps({{'utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'ok':ok,'verification_sha256':hashlib.sha256(v.read_bytes()).hexdigest()}},indent=2)+'\\n')
assert ok,'two-step fixture not exact'
print('Two-step A100 fixture exact. No scientific training launched.',flush=True)
PY
"""
    (SETUP / "worker_bootstrap_hr.sh").write_text(bootstrap)
    setup_files = {name: SETUP / name for name in ("bootstrap_hr.sh", "setup_and_fetch_hr.sh", "download_models_hr.py",
                                                  "worker_bootstrap_hr.sh", "lead_pipeline.py", "job_runner.py",
                                                  "bundle-hr-v1.tar.gz")}
    setup_files["process_receipt.py"] = OLD / "process_receipt.py"
    setup_files["requirements.lock"] = ROOT / "experiments/minimal_safety/requirements.lock"
    setup_files["expanded-assets-v2.tar.gz"] = ASSETS
    setup = SETUP / "worker-setup-hr.tar.gz"
    tar(setup, setup_files)
    receipt = {"utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "git_commit": commit, "engine_sha256": code,
               "recipe_path": a.recipe, "bundle": {"path": str(bundle), "sha256": bundle_sha, "files": len(files)},
               "setup": {"path": str(setup), "sha256": sha(setup), "bytes": setup.stat().st_size},
               "members": {name: sha(f) for name, f in sorted(setup_files.items())}}
    with (SETUP / "setup-receipt.json").open("x") as handle:
        handle.write(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({k: receipt[k] for k in ("git_commit", "engine_sha256", "bundle", "setup")}, indent=2))


if __name__ == "__main__":
    main()
